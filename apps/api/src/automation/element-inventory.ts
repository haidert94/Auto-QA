// Convierte el inventario crudo que captura el crawler de Exploración
// (apps/explorer/src/explorer.ts) en texto que los agentes de generación
// pueden citar literalmente como paso DSL (click:/click-text:/fill:/
// fill-label:). Deliberadamente NO importamos tipos de apps/explorer: un
// import cruzado entre paquetes ya rompió una vez el build de producción
// (ver commit "fix(api): move the pipeline runner into api to preserve
// dist/app.js"), así que el tipo se redeclara acá — es solo un shape plano.
//
// Prioridad de selector (de más a menos estable):
//   1. data-testid / data-test-id / data-test / data-cy / data-qa — puesto
//      a propósito para testing, nunca cambia por un refactor de estilos.
//   2. Texto visible (botones/links) o etiqueta asociada (inputs) — usa
//      click-text:/fill-label:, que Playwright resuelve por accesibilidad
//      y sobrevive a cambios de clases/ids.
//   3. name — estable en formularios.
//   4. id, solo si no parece generado por una librería de UI (Radix,
//      MUI, Mantine, React useId) ni por el render (sufijo numérico largo).
import type { PrismaClient } from '@prisma/client';

export type RawElement = {
  tag: string; type?: string; testid?: string; testidAttr?: string; id?: string; name?: string;
  text?: string; label?: string; href?: string;
};

type SelectorCandidate = { value: string; kind: 'testid' | 'text' | 'label' | 'name' | 'id' };

function looksAutoGenerated(id: string): boolean {
  return /^[a-f0-9]{8,}$/i.test(id)
    || /^(radix|mantine|mui|headlessui|chakra)-/i.test(id)
    || /^:[\w-]+:$/.test(id)
    || /-\d{4,}$/.test(id);
}

function escapeAttributeValue(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

// Elige el selector más estable para un elemento clickeable (click:) o
// rellenable (fill:). El "kind" decide si se prefiere texto o etiqueta.
function selectorFor(el: RawElement, mode: 'click' | 'fill'): SelectorCandidate | null {
  if (el.testid && el.testidAttr) {
    return { value: `[${el.testidAttr}="${escapeAttributeValue(el.testid)}"]`, kind: 'testid' };
  }
  if (mode === 'click' && el.text) return { value: el.text, kind: 'text' };
  if (mode === 'fill' && el.label) return { value: el.label, kind: 'label' };
  if (el.name) return { value: `[name="${escapeAttributeValue(el.name)}"]`, kind: 'name' };
  if (el.id && !looksAutoGenerated(el.id)) return { value: `#${escapeIdSelector(el.id)}`, kind: 'id' };
  return null;
}

// Escape mínimo para usar un id como selector CSS (#id). No usamos
// CSS.escape porque este módulo corre en Node, no en el navegador.
function escapeIdSelector(id: string): string {
  return id.replace(/([^\w-])/g, '\\$1');
}

// Convierte un elemento a la línea de prompt exacta que el agente puede
// citar como "action" de un paso. Devuelve null si el elemento no tiene
// ninguna pista utilizable (ya filtrado en la extracción, pero por si acaso).
export function formatElementLine(el: RawElement): string | null {
  const clickable = el.tag === 'button' || el.tag === 'a';
  const fillable = el.tag === 'input' || el.tag === 'select' || el.tag === 'textarea';
  if (clickable) {
    const candidate = selectorFor(el, 'click');
    if (!candidate) return null;
    const verb = candidate.kind === 'text' ? 'click-text' : 'click';
    const hint = el.href ? ` (enlace a ${el.href})` : '';
    return `${verb}: ${candidate.value}${hint}`;
  }
  if (fillable) {
    const candidate = selectorFor(el, 'fill');
    if (!candidate) return null;
    const verb = candidate.kind === 'label' ? 'fill-label' : 'fill';
    const typeHint = el.type && el.type !== 'text' ? ` (type=${el.type})` : '';
    return `${verb}: ${candidate.value}${typeHint}`;
  }
  return null;
}

function pagePath(url: string): string {
  try {
    const parsed = new URL(url);
    return (parsed.pathname + parsed.search) || '/';
  } catch {
    return url.slice(0, 120);
  }
}

// Condensa el inventario de varias páginas en texto listo para el prompt.
// Deduplica líneas repetidas (un mismo componente de nav aparece en cada
// página) y corta a `limit` líneas en total para no inflar el prompt.
export function buildElementInventoryContext(
  pages: Array<{ url: string; elements: RawElement[] }>,
  limit = 150,
): string {
  const seen = new Set<string>();
  const lines: string[] = [];
  for (const page of pages) {
    if (lines.length >= limit) break;
    const pageLines: string[] = [];
    for (const el of page.elements) {
      if (lines.length + pageLines.length >= limit) break;
      const line = formatElementLine(el);
      if (!line || seen.has(line)) continue;
      seen.add(line);
      pageLines.push(line);
    }
    if (pageLines.length) {
      lines.push(`# ${pagePath(page.url)}`, ...pageLines);
    }
  }
  return lines.join('\n');
}

// Lee la exploración COMPLETED más reciente para el proyecto+entorno y
// devuelve sus páginas con el inventario crudo ya parseado. Degrada a
// array vacío si no hay exploraciones, el entorno no coincide, o las
// páginas no tienen inventario (exploraciones previas a esta feature).
export async function latestExplorationInventory(
  prisma: Pick<PrismaClient, 'exploration'>,
  projectId: string,
  environmentId: string | null,
): Promise<Array<{ url: string; elements: RawElement[] }>> {
  if (!environmentId) return [];
  if (!prisma.exploration?.findFirst) return [];
  const exploration = await prisma.exploration.findFirst({
    where: { projectId, environmentId, status: 'COMPLETED' },
    orderBy: { finishedAt: 'desc' },
    select: { pages: { select: { url: true, elements: true }, orderBy: { position: 'asc' } } },
  });
  if (!exploration) return [];
  return exploration.pages
    .filter((page): page is typeof page & { elements: NonNullable<typeof page.elements> } =>
      Array.isArray(page.elements) && page.elements.length > 0)
    .map(page => ({ url: page.url, elements: page.elements as unknown as RawElement[] }));
}
